# 등급 → 숫자 (분류 평가용)
GRADE_RANK = {
    "신뢰 가능": 4,
    "주의 필요": 3,
    "의심 기사": 2,
    "신뢰 낮음": 1,
}


def grade_distance(expected, actual):
    """예상 등급과 실제 등급 간 거리. 0=정확, 1=인접, 2이상=틀림."""
    return abs(GRADE_RANK.get(expected, 0) - GRADE_RANK.get(actual, 0))
